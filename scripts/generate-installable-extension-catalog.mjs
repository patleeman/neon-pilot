#!/usr/bin/env node
/* eslint-env node */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const installableRoot = join(repoRoot, 'installable-extensions');
const outputPath = join(repoRoot, 'packages', 'desktop', 'server', 'extensions', 'installableExtensionCatalog.generated.ts');
const checkOnly = process.argv.includes('--check');

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function normalizeString(value, fallback) {
  return typeof value === 'string' && value.trim() ? value.trim() : fallback;
}

function listCatalogItems() {
  if (!existsSync(installableRoot)) return [];
  return readdirSync(installableRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const manifestPath = join(installableRoot, entry.name, 'extension.json');
      if (!existsSync(manifestPath)) return null;
      const manifest = readJson(manifestPath);
      const id = normalizeString(manifest.id, entry.name);
      return {
        id,
        name: normalizeString(manifest.name, id),
        description: normalizeString(manifest.description, 'No description provided.'),
        ...(manifest.packageType === 'extension' ||
        manifest.packageType === 'skill' ||
        manifest.packageType === 'instruction-pack' ||
        manifest.packageType === 'agent' ||
        manifest.packageType === 'template'
          ? { packageType: manifest.packageType }
          : {}),
        ...(manifest.ecosystem === 'neon-pilot' || manifest.ecosystem === 'codex' || manifest.ecosystem === 'claude'
          ? { ecosystem: manifest.ecosystem }
          : {}),
        ...(typeof manifest.marketplaceSourceId === 'string' && manifest.marketplaceSourceId.trim()
          ? { marketplaceSourceId: manifest.marketplaceSourceId.trim() }
          : {}),
      };
    })
    .filter(Boolean)
    .sort((left, right) => left.id.localeCompare(right.id));
}

const catalog = listCatalogItems();
const source = `// Generated by scripts/generate-installable-extension-catalog.mjs. Do not edit by hand.

import type { CatalogSeed } from './extensionCatalog.js';

export const INSTALLABLE_EXTENSION_CATALOG: CatalogSeed[] = ${JSON.stringify(catalog, null, 2)};
`;

const nextSource = `${source}\n`;
if (checkOnly) {
  const currentSource = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (currentSource !== nextSource) {
    throw new Error(
      `${outputPath.replace(`${repoRoot}/`, '')} is out of date. Run node scripts/generate-installable-extension-catalog.mjs.`,
    );
  }
  console.log(`Installable extension catalog is current with ${catalog.length} entries.`);
} else {
  writeFileSync(outputPath, nextSource, 'utf8');
  console.log(`Generated ${outputPath.replace(`${repoRoot}/`, '')} with ${catalog.length} installable extensions.`);
}
