#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';

const repoRoot = resolve(new URL('..', import.meta.url).pathname);
const tsxBin = resolve(repoRoot, 'node_modules/.bin/tsx');
const cliSource = pathToFileURL(resolve(repoRoot, 'packages/desktop/server/protocolCli.ts')).href;
const outputPath = resolve(repoRoot, 'docs/cli-reference.md');
const check = process.argv.includes('--check');

function runCli(args) {
  const tempDir = mkdtempSync(join(tmpdir(), 'neon-cli-reference-'));
  const stdoutPath = join(tempDir, 'stdout.txt');
  try {
    const result = spawnSync(tsxBin, ['--eval', oneShotCliEval(args, stdoutPath)], {
      cwd: repoRoot,
      encoding: 'utf-8',
      timeout: 60_000,
      maxBuffer: 8 * 1024 * 1024,
      env: { ...process.env, NEON_PILOT_REPO_ROOT: process.env.NEON_PILOT_REPO_ROOT || repoRoot, NEON_PILOT_FORCE_SOURCE_CLI: '1' },
    });
    const stdout = existsSync(stdoutPath) ? readFileSync(stdoutPath, 'utf-8') : result.stdout;
    if (result.status !== 0) {
      throw new Error(result.stderr || stdout || `neon-pilot ${args.join(' ')} exited with ${result.status}`);
    }
    return stdout;
  } finally {
    rmSync(tempDir, { recursive: true, force: true });
  }
}

function oneShotCliEval(args, stdoutPath) {
  return [
    `import { appendFileSync } from 'node:fs';`,
    `import(${JSON.stringify(cliSource)})`,
    `  .then(async (module) => {`,
    `    const stdoutPath = ${JSON.stringify(stdoutPath)};`,
    `    const originalWrite = process.stdout.write.bind(process.stdout);`,
    `    process.stdout.write = ((chunk, encoding, callback) => {`,
    `      appendFileSync(stdoutPath, typeof chunk === 'string' ? chunk : Buffer.from(chunk).toString(typeof encoding === 'string' ? encoding : undefined));`,
    `      if (typeof encoding === 'function') encoding();`,
    `      else if (typeof callback === 'function') callback();`,
    `      return true;`,
    `    });`,
    `    await module.main(${JSON.stringify(args)});`,
    `    process.stdout.write = originalWrite;`,
    `    process.exit(process.exitCode ?? 0);`,
    `  })`,
    `  .catch((error) => {`,
    `    console.error(error instanceof Error ? error.stack || error.message : String(error));`,
    `    process.exit(1);`,
    `  });`,
  ].join('\n');
}

function renderCommand(command) {
  const lines = [`### ${command.command}`, ''];
  lines.push(command.description ?? command.title ?? '');
  lines.push('');
  lines.push(`- Source: ${command.source ?? 'extension'}${command.extensionId ? ` (${command.extensionId})` : ''}`);
  lines.push(`- Usage: \`neon-pilot ${command.usage ?? command.command}\``);
  lines.push(`- Mode: ${command.mode ?? 'unknown'}`);
  lines.push(`- Requires app: ${command.requiresApp === true ? 'yes' : 'no'}`);
  lines.push(`- Idempotent: ${command.idempotent === true ? 'yes' : 'no'}`);
  lines.push(`- Destructive: ${command.destructive === true ? 'yes' : 'no'}`);
  lines.push(`- Dry run: ${command.supportsDryRun === true ? 'yes' : 'no'}`);
  lines.push(`- Output: ${(command.outputModes ?? ['text']).join(', ')}`);
  if (command.aliases?.length) lines.push(`- Aliases: ${command.aliases.map((alias) => `\`${alias}\``).join(', ')}`);
  if (command.examples?.length) {
    lines.push('', 'Examples:', '');
    for (const example of command.examples) lines.push(`- \`${example}\``);
  }
  return `${lines.join('\n')}\n`;
}

function renderReference(commands) {
  const sorted = [...commands].sort((a, b) => a.command.localeCompare(b.command));
  return [
    '# Neon Pilot CLI Reference',
    '',
    '<!-- Generated by scripts/generate-cli-reference.mjs. Do not edit by hand. -->',
    '',
    `Generated from \`neon-pilot commands --json\` with ${sorted.length} commands.`,
    '',
    ...sorted.map(renderCommand),
  ].join('\n');
}

const parsed = JSON.parse(runCli(['commands', '--json']));
const commands = Array.isArray(parsed.commands) ? parsed.commands : [];
const next = renderReference(commands);

if (check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf-8') : '';
  if (current !== next) {
    console.error('docs/cli-reference.md is stale. Run pnpm run docs:cli.');
    process.exit(1);
  }
  console.log('CLI reference is current.');
} else {
  writeFileSync(outputPath, next);
  console.log(`Wrote ${outputPath}`);
}
